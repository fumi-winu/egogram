function silentFactorNote(result: DiagnosisResult): string | null {
  const ranked = FACTOR_ORDER.map((factor) => ({
    factor,
    percentile: result.percentiles[factor],
  })).sort((a, b) => a.percentile - b.percentile);

  const quiet = ranked.filter((item) => item.percentile <= 40);
  if (quiet.length === 0) return null;

  const names = quiet.map((item) => FACTOR_INFO[item.factor].name).join("・");
  return `いま沈黙している通路は${names}です。前面の強みを伸ばすだけでなく、沈黙している通路を週に一度でも使うことが、虚無への備えになります。低く出た因子は欠陥ではなく、まだ十分に使っていない水源です。`;
}

export function compileDeepReport(result: DiagnosisResult): CompiledDeepReport {
  const factorReadings = FACTOR_ORDER.map((factor) => {
    const band = getScoreBand(result.percentiles[factor]);
    return {
      factor,
      band,
      paragraphs: FACTOR_DEEP[factor][band],
    };
  });

  return {
    result,
    opening: [
      `このレポートは、あなたの類型「${result.type.name}（${result.type.nameEn}）」と、創造・体験・態度・実存的自律の四因子の配置を、無料結果より長い射程で読み直したものです。類型は箱ではなく、意味が通りやすい地形の予報です。`,
      "フランクルは、意味を捏造するものではなく、状況のなかで発見し、応答するものとしました。以下の文章は医学的診断の代替ではなく、あなたが今週どのように応答するかを考えるための語彙です。",
    ],
    factorReadings,
    silentNote: silentFactorNote(result),
    guide: TYPE_DEEP[result.type.id],
    closing:
      "深層分析の目的は、あなたを一つの物語に固定することではありません。今夜、一つの通路を選び、未完のまま世界に返すこと。それが、このレポートの最後の処方箋です。",
  };
}
