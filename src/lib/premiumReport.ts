function chapter(
  number: 1 | 2 | 3 | 4 | 5,
  lead: string,
  paragraphs: string[],
  extras?: Partial<Pick<PremiumChapter, "callouts" | "anchor" | "weeks">>,
): PremiumChapter {
  const meta = CHAPTER_META[number];
  return {
    number,
    title: meta.title,
    subtitle: meta.subtitle,
    lead,
    paragraphs,
    callouts: extras?.callouts ?? [],
    anchor: extras?.anchor ?? null,
    weeks: extras?.weeks ?? [],
  };
}

function placementsFrom(result: DiagnosisResult): FactorPlacement[] {
  const ranked = [...FACTOR_ORDER]
    .map((factor) => ({
      factor,
      percentile: result.percentiles[factor],
    }))
    .sort((a, b) => b.percentile - a.percentile);

  return ranked.map((item, index) => {
    const band = getScoreBand(item.percentile);
    const info = FACTOR_INFO[item.factor];
    return {
      factor: item.factor,
      name: info.name,
      nameEn: info.nameEn,
      score: result.scores[item.factor],
      maxScore: MAX_SCORE_PER_FACTOR,
      percentile: item.percentile,
      band,
      bandLabel: SCORE_BAND_LABEL[band],
      rank: index + 1,
    };
  });
}

function rankNarrative(placements: FactorPlacement[]): string {
  const order = placements
    .map((item) => `${item.name}（${item.percentile}%）`)
    .join(" → ");
  const dominant = placements[0];
  const quiet = placements[placements.length - 1];
  if (!dominant || !quiet) {
    return "四因子の配置を、類型の地形として読みます。";
  }

  const range = dominant.percentile - quiet.percentile;
  if (range <= 15) {
    return `本鑑定における四因子の配置は、${order}です。首位と最下位の差は${range}ポイントにとどまり、特定の通路への固定が小さい地形です。突出のなさは欠陥ではなく、意味の通り方がまだ一つに収束していないか、使い分けが可能な状態を示します。`;
  }

  return `本鑑定における四因子を高い順に並べると、${order}です。首位の${dominant.name}（${dominant.percentile}%・${dominant.bandLabel}）が、いま意味が通りやすい主通路です。最下位の${quiet.name}（${quiet.percentile}%・${quiet.bandLabel}）は欠陥ではなく、無意識の優先順位では後景に退いている予備の井戸です。`;
}

function tensionNarrative(placements: FactorPlacement[]): string | null {
  const dominant = placements[0];
  const quiet = placements[placements.length - 1];
  if (!dominant || !quiet) return null;
  if (dominant.percentile - quiet.percentile < 20) return null;

  const key = `${dominant.factor}:${quiet.factor}` as `${Factor}:${Factor}`;
  return TENSION[key] ?? null;
}

function silentNote(placements: FactorPlacement[]): string | null {
  const quiet = placements.filter((item) => item.percentile <= 40);
  if (quiet.length === 0) return null;
  const names = quiet.map((item) => item.name).join("・");
  return `いま沈黙している通路は${names}です。前面の強みを伸ばすだけでなく、沈黙している通路を週に一度でも意識的に使うことが、虚無への備えになります。低く出た因子は欠陥ではなく、まだ十分に使っていない水源です。`;
}

function formatIssuedOn(purchasedAt: Date): string {
  return purchasedAt.toLocaleDateString("ja-JP", {
    timeZone: "Asia/Tokyo",
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

export function compilePremiumReport(
  result: DiagnosisResult,
  meta: { purchasedAt: Date; sessionId: string },
): CompiledPremiumReport {
  const copy = TYPE_PREMIUM[result.type.id];
  const factorPlacements = placementsFrom(result);
  const dominant = factorPlacements[0];
  const quiet = factorPlacements[factorPlacements.length - 1];
  if (!dominant || !quiet) {
    throw new Error("四因子の配置を構築できませんでした。");
  }

  const factorReadings = factorPlacements.map((item) => {
    const anatomy = FACTOR_ANATOMY[item.factor][item.band];
    return `${item.name}は${item.score}/${item.maxScore}（${item.percentile}%・${item.bandLabel}）です。${anatomy}`;
  });

  const tension = tensionNarrative(factorPlacements);
  const silent = silentNote(factorPlacements);
  const anatomyParagraphs = [
    rankNarrative(factorPlacements),
    ...factorReadings,
    ENERGY_SOURCE[dominant.factor],
    ENERGY_DRAIN[dominant.factor],
    ...(tension ? [tension] : []),
    ...(silent ? [silent] : []),
    ...copy.anatomy,
  ];

  const careerParagraphs = [
    ...copy.career,
    CAREER_OVERLAY[dominant.factor][dominant.band],
    ...(dominant.factor !== quiet.factor
      ? [CAREER_OVERLAY[quiet.factor][quiet.band]]
      : []),
  ];

  const relationParagraphs = [
    ...copy.relationships,
    RELATION_OVERLAY[dominant.factor][dominant.band],
    ...(dominant.factor !== quiet.factor
      ? [RELATION_OVERLAY[quiet.factor][quiet.band]]
      : []),
  ];

  const chapters: PremiumChapter[] = [
    chapter(1, copy.anatomyLead, anatomyParagraphs),
    chapter(2, copy.careerLead, careerParagraphs, {
      callouts: [
        { heading: "避けるべき組織文化", items: copy.avoidCultures },
        { heading: "消耗するタスクの構造", items: copy.drainingTasks },
      ],
    }),
    chapter(3, copy.relationLead, relationParagraphs, {
      callouts: [
        { heading: "協働・親密さにおける摩擦要因", items: copy.friction },
        { heading: "調和の鍵", items: copy.harmony },
      ],
    }),
    chapter(4, copy.crisisLead, copy.darkSide, {
      callouts: [
        { heading: "危機を感じたときの立ち戻り", items: copy.recovery },
      ],
      anchor: {
        heading: "実存のアンカー（拠り所）",
        body: copy.anchor,
      },
    }),
    chapter(
      5,
      "第1週から第4週まで、日常で実践できる内省と行動の指針です。観察、境界、開示、定着の順に進めてください。",
      [],
      { weeks: copy.weeks },
    ),
  ];

  return {
    documentTitle: PREMIUM_DOCUMENT_TITLE,
    typeName: result.type.name,
    typeNameEn: result.type.nameEn,
    tagline: result.type.tagline,
    issuedOn: formatIssuedOn(meta.purchasedAt),
    sessionId: meta.sessionId,
    factorPlacements,
    dominant,
    quiet,
    chapters,
    closing: copy.closing,
    disclaimer:
      "本鑑定書は医学的診断、心理療法、職業適性検査の代替ではありません。ヴィクトール・E・フランクルの実存分析・ロゴセラピーに着想した動機配置の読解であり、今週どのように応答するかを考えるための語彙です。類型は箱ではなく、意味が通りやすい地形の予報です。",
  };
}
